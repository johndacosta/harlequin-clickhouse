def clickhouse_completions() -> list[HarlequinCompletion]:
    """ClickHouse tokens for the editor. Not the placeholder set foo/bar/baz."""
    keywords = [
        HarlequinCompletion(
            label=item,
            type_label="kw",
            value=item,
            priority=100,
            context=None,
        )
        for item in _KEYWORDS
    ]
    functions = [
        HarlequinCompletion(
            label=item,
            type_label="fn",
            value=item,
            priority=1000,
            context=None,
        )
        for item in _FUNCTIONS
    ]
    return [*keywords, *functions]
